import 'dart:io';

import 'package:ffigen/ffigen.dart';

Future<void> main() async {
  final packageRoot = Platform.script.resolve('../');
  final header = packageRoot.resolve('src/native/include/just_image.h');
  final bindings = packageRoot.resolve('lib/src/native_bindings.g.dart');
  final recordUseMapping = packageRoot.resolve(
    'lib/src/native_bindings.record_use_mapping.g.dart',
  );

  const functions = {
    'rust_abi_version',
    'rust_process_pipeline',
    'rust_process_core_pipeline',
    'rust_process_extended_pipeline',
    'rust_free_buffer',
    'rust_free_error',
    'rust_version',
    'rust_free_string',
    'rust_image_info',
    'rust_blurhash_encode',
    'rust_blurhash_decode',
    'rust_available_filters',
  };

  await FfiGenerator(
    input: Input(entryPoints: [header]),
    visitors: [
      Visitor(
        func: (node) {
          node.isIncluded = functions.contains(node.originalName);
          node.recordUse = node.isIncluded;
          node.isLeaf =
              node.originalName.startsWith('rust_free_') ||
              node.originalName == 'rust_abi_version';
        },
        struct: (node) => node.isIncluded = node.originalName == 'FfiResult',
      ),
    ],
    output: Output(
      dart: DartOutput(path: bindings),
      recordUseMapping: recordUseMapping,
      style: const NativeExternalBindings(
        assetId: 'package:just_image/src/native_bindings.g.dart',
      ),
      preamble: '''
// Copyright (c) 2026 just_image contributors.
// SPDX-License-Identifier: MIT
// Generated by package:ffigen. Do not edit manually.
// Regenerate with: dart run tool/ffigen.dart

// ignore_for_file: type=lint, camel_case_types, non_constant_identifier_names
''',
    ),
  ).generate();
}
